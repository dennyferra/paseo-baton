import { describe, expect, it } from "vitest";
import {
  buildContinuePrompt,
  buildWriterHandoffPrompt,
  extractHandoffDocument,
  extractTitleFromDocument,
  stampHandoffDocument,
  stripAttributionLines,
} from "../server/handoff";

describe("extractTitleFromDocument", () => {
  it("prefers the explicit Title line", () => {
    const doc = "Title: Fix flaky login test\n\n# Task\nInvestigate why the login spec fails intermittently on CI.\n";
    expect(extractTitleFromDocument(doc, "untitled task")).toBe("Fix flaky login test");
  });

  it("falls back to the first line of the Task section", () => {
    expect(extractTitleFromDocument("# Task\nAdd retries\n# Context\nx\n", "untitled task")).toBe("Add retries");
  });
});

describe("stampHandoffDocument", () => {
  const NOW = Date.UTC(2026, 9, 19, 12, 0, 0);
  const STAMP = "Created: 2026-10-19T12:00:00.000Z";

  it("puts the timestamp right under the Title line", () => {
    expect(stampHandoffDocument("Title: Fix login\n\n# Task\nx\n", NOW)).toBe(`Title: Fix login\n${STAMP}\n\n# Task\nx\n`);
  });

  it("puts the timestamp at the top when there is no Title line", () => {
    expect(stampHandoffDocument("# Task\nx\n", NOW)).toBe(`${STAMP}\n# Task\nx\n`);
  });

  it("replaces a Created line the writer added but leaves body text alone", () => {
    const doc = "Title: Fix login\nCreated: yesterday\n\n# Task\nCreated: a new endpoint\n";
    expect(stampHandoffDocument(doc, NOW)).toBe(`Title: Fix login\n${STAMP}\n\n# Task\nCreated: a new endpoint\n`);
  });
});

describe("stripAttributionLines", () => {
  it("drops commit trailers and Generated-with lines", () => {
    const text = [
      "- Keep the diff small",
      "- Commit trailers: `Co-Authored-By: Claude Haiku 5.5 <noreply@anthropic.com>` on commits",
      "Co-authored-by: Someone Else <someone@example.com>",
      "- PR bodies: `🤖 Generated with [Claude Code](https://claude.com/claude-code)`",
      "- Run the tests first",
    ].join("\n");
    expect(stripAttributionLines(text)).toBe(
      "- Keep the diff small\n- PR bodies: `🤖 [attribution removed]`\n- Run the tests first",
    );
  });

  it("drops trailers without an email and Unicode look-alikes", () => {
    const text = ["Co-Authored-By: Claude Haiku 5.5", "Co\u2011authored by: Someone", "Co-Authored-By\uFF1A Someone", "Generated with Claude Code", "kept"].join("\n");
    expect(stripAttributionLines(text)).toBe("kept");
  });

  it("drops bold, escaped, spaced, table and assisted-by forms", () => {
    const text = [
      "- **Co-Authored-By**: Claude Haiku 5.5 <noreply@anthropic.com>",
      "Co Authored-By: Claude Haiku 5.5",
      "Co\\-Authored\\-By: Claude Haiku 5.5",
      "| Co-Authored-By | Claude Haiku 5.5 |",
      "Assisted-by: Claude Haiku 5.5",
      "kept",
    ].join("\n");
    expect(stripAttributionLines(text)).toBe("kept");
  });

  it("takes the value line of a trailer label that has none, but not the next table row", () => {
    expect(stripAttributionLines("Co-Authored-By:\nClaude Haiku 5.5 <x@y.z>\nkept")).toBe("kept");
    expect(stripAttributionLines("| Co-Authored-By | Claude |\n| Other | row |")).toBe("| Other | row |");
  });

  it("keeps transcript lines of the fallback draft, such as pasted git log output", () => {
    const text = "> user: please keep going. git log shows Co-authored-by: Alice <alice@example.com> on abc123, fix the rest\n> assistant: ok";
    expect(stripAttributionLines(text)).toBe(text);
  });

  it("does not take a heading, list item or table row after a bare label", () => {
    expect(stripAttributionLines("Co-Authored-By:\n# Next section\nkept")).toBe("# Next section\nkept");
    expect(stripAttributionLines("Co-Authored-By:\n- keep this item")).toBe("- keep this item");
  });

  it("stays fast on a long line of repeated decoration", () => {
    const started = Date.now();
    stripAttributionLines(`${"* ".repeat(20_000)}x`);
    stripAttributionLines(`${"co authored ".repeat(5_000)}`);
    expect(Date.now() - started).toBeLessThan(1_000);
  });

  it("replaces a mid-line trailer that names a model, with or without an email or colon, and zero-width splits, keeping the sentence", () => {
    const text = [
      "- Always add `Co-Authored-By: Claude Haiku 5.5` to commits",
      "- Add Co-authored-by Claude <noreply@anthropic.com> to every commit",
      "- Footer: Generated-by: Gemini 3",
      "- Co\u200B-Authored-By: Claude Haiku 5.5 <x@y.z>",
      "kept",
    ].join("\n");
    expect(stripAttributionLines(text)).toBe(
      [
        "- Always add `[attribution removed] Haiku 5.5` to commits",
        "- Add [attribution removed] to every commit",
        "- Footer: [attribution removed] 3",
        "kept",
      ].join("\n"),
    );
  });

  it("keeps prose that talks about AI tools or people, and a human's sign-off", () => {
    const lines = [
      "- `nextCursor` is generated by `cursorFrom(row)` in db/pager.ts",
      "- Test fixtures were generated by an AI and still need a human review",
      "- PRs assisted by an AI tool must carry the ai-assisted label",
      "- The migration was generated by Codex in the previous session; check it",
      "- Column `generated_by_claude` marks rows the importer made",
      "- .cursor/rules files are generated by cursor-rules-gen",
      "- Design signed off by Anthropic legal on Friday",
      "- Setup assisted by the README; clone <ssh://git@github.com/org/repo.git>",
      "- Deployment assisted by Bob; ping <bob@example.com> first",
      "- Signed-off-by: Claude Dupont <claude.dupont@example.fr>",
      "- Signed-off-by: Alice <alice@example.com> is the DCO line the repo needs",
      // Names and identifiers that hold a label: a flag, a file, a CSS class, a binding, a person to contact.
      "- Added a `--generated-by-cursor` flag to the exporter CLI",
      "- Renamed fixtures/generated-by-openai.json to fixtures/openai.json",
      "- The CSS class .assisted-by-copilot hides the badge",
      "- Ported generated-by-llama.cpp bindings to node",
      "- Contact co_authored_by owner: see <ops@example.com>",
      "- The `assisted-by-claude` label is set by the triage bot",
      "- See generated-by-gpt/README.md before editing",
      "- The co-authored-bylaws file is unrelated",
    ];
    expect(stripAttributionLines(lines.join("\n"))).toBe(lines.join("\n"));
  });

  it("never drops a whole line for a mid-line trailer: it keeps the sentence and puts a marker where the trailer was", () => {
    const cases: Array<[string, string]> = [
      [
        "- Next: grep for co-authored-by: claude in .git/hooks/commit-msg and remove it",
        "- Next: grep for [attribution removed] in .git/hooks/commit-msg and remove it",
      ],
      [
        "- PR #12 body says Assisted-by: Copilot; ask the operator whether to keep it",
        "- PR #12 body says [attribution removed]; ask the operator whether to keep it",
      ],
      [
        "- Fixed the stripper so `Co-Authored-By: Claude` lines no longer reach the next session",
        "- Fixed the stripper so `[attribution removed]` lines no longer reach the next session",
      ],
      [
        "- Wrote tests where assisted-by=claude query param is parsed",
        "- Wrote tests where [attribution removed] query param is parsed",
      ],
      [
        "- `git log` shows co-authored-by trailers for alice <alice@corp.com>",
        "- `git log` shows [attribution removed]",
      ],
      [
        "- Open the PR with Generated with [Claude Code](https://claude.com/claude-code) cleared",
        "- Open the PR with [attribution removed] cleared",
      ],
    ];
    for (const [line, expected] of cases) {
      expect(stripAttributionLines(line)).toBe(expected);
    }
  });

  it("finds a trailer after an escaped line break in a one-line commit message, or after a dot, slash or equals sign", () => {
    const cases: Array<[string, string]> = [
      [
        '- Run git commit -m "Fix login\\n\\nCo-Authored-By: Claude Haiku 5.5 <noreply@anthropic.com>" for each fix',
        '- Run git commit -m "Fix login  [attribution removed]" for each fix',
      ],
      ["- Set trailer=Generated-by: Claude in the config", "- Set trailer=[attribution removed] in the config"],
      ["- Footer text.Co-Authored-By: Claude <x@y.z>", "- Footer text.[attribution removed]"],
    ];
    for (const [line, expected] of cases) {
      const out = stripAttributionLines(line);
      expect(out).not.toContain("noreply@anthropic.com");
      expect(out).toBe(expected);
    }
  });

  it("drops a line that is only a trailer, whatever its decoration", () => {
    expect(stripAttributionLines("- `Co-Authored-By=ChatGPT`\n> Co-Authored-By Claude <x@y.z>\nkept")).toBe("kept");
  });

  it("replaces a pasted human co-author with an email, by design", () => {
    expect(stripAttributionLines("- Credit: Co-authored-by: Alice <alice@example.com>\nkept")).toBe(
      "- Credit: [attribution removed]\nkept",
    );
  });

  it("drops quoted, bracketed and more vendor names after a joined label, and invisible characters", () => {
    const text = [
      "- Co-Authored-By: 'Claude'",
      "- Co-Authored-By: GitHub Copilot",
      "- Co-Authored-By=ChatGPT",
      "- Co-Authored-By \u2014 DeepSeek",
      "- Co-Auth\u2063ored-By: Claude",
      "kept",
    ].join("\n");
    expect(stripAttributionLines(text)).toBe("kept");
  });

  it("stays linear on long pathological lines", () => {
    const started = Date.now();
    stripAttributionLines("co-authored-by".concat(" ".repeat(20)).repeat(5_000));
    stripAttributionLines("assisted by".concat(" ".repeat(21)).repeat(5_000));
    stripAttributionLines(`${"co-authored-by ".repeat(300)}<${"@".repeat(3_000)}`);
    stripAttributionLines(`co-authored-by <${"@".repeat(50_000)}`);
    expect(Date.now() - started).toBeLessThan(2_000);
  });

  it("exempts only the fallback draft's own transcript lines, not quoted or reshaped ones", () => {
    const own = "> user: git log shows Co-authored-by: Alice <alice@example.com>\n> assistant: ok";
    expect(stripAttributionLines(own)).toBe(own);
    const note = "Co-Authored-By: Claude Haiku 5.5 <noreply@anthropic.com>";
    for (const prefix of ["> > user: ", ">> assistant: ", ">user: "]) {
      expect(stripAttributionLines(`${prefix}${note}`)).not.toContain("noreply@anthropic.com");
    }
  });

  it("keeps a constraint that only talks about trailers", () => {
    const text = "- Commits must not carry Co-Authored-By: lines; use the session's own\n- Title: Strip Co-authored-by: trailers";
    expect(stripAttributionLines(text)).toBe(text);
  });

  it("keeps prose that only mentions the words", () => {
    const text = "The draft PR text lists Co-Authored-By lines for two models.\nGenerated with care.";
    expect(stripAttributionLines(text)).toBe(text);
  });
});

describe("extractHandoffDocument", () => {
  it("strips attribution from the writer's reply", () => {
    const reply = "```markdown\n# Task\nShip it\n\n# Constraints\nCo-Authored-By: Claude Haiku 5.5 <noreply@anthropic.com>\nKeep it small\n```";
    expect(extractHandoffDocument([{ type: "assistant_message", text: reply }])).toBe(
      "# Task\nShip it\n\n# Constraints\nKeep it small\n",
    );
  });

  it("returns null when the reply is not a handoff", () => {
    expect(extractHandoffDocument([{ type: "assistant_message", text: "Sorry, no." }])).toBeNull();
  });
});

describe("buildWriterHandoffPrompt", () => {
  const prompt = buildWriterHandoffPrompt("DRAFT BODY");

  it("forbids invented attribution and facts", () => {
    expect(prompt).toContain("Never add facts of your own");
    expect(prompt).toContain("no commit trailers");
    expect(prompt).toContain("Copy the Provider, Agent and Working directory values from the draft");
  });

  it("asks for draft-derived state to be marked as of the Generated time and unverified", () => {
    expect(prompt).toContain("As of <the Generated time>, unverified:");
    expect(prompt).toContain("Verify before acting:");
  });

  it("puts the draft last", () => {
    expect(prompt.endsWith("## Machine draft\n\nDRAFT BODY")).toBe(true);
  });
});

describe("buildContinuePrompt", () => {
  it("tells the new session to check state before acting and not to copy attribution", () => {
    const prompt = buildContinuePrompt("/work/.paseo/handoffs/a.md", "# Task\nx\n");
    expect(prompt).toContain("check the real state");
    expect(prompt).toContain("Do not copy commit trailers or other attribution");
    expect(prompt.endsWith("Continue the task it describes.")).toBe(true);
  });
});
